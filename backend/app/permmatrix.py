"""Writes docs/PERMISSIONS.md: which role can read which module, measured against the running API (not copied from comments).

    cd backend && .venv/bin/python -m app.permmatrix > ../docs/PERMISSIONS.md

It seeds a throw-away SQLite database, signs in as one demo user per role and calls every GET endpoint that takes no id. A cell shows
"readable endpoints / endpoints in the module". The write rules (who may create, approve, delete) are listed from the role sets written
in each router file; tests/test_authz.py proves the isolation between buildings and tests/test_security.py the account rules.
"""
import logging
import os
import re
import sys
import tempfile
from pathlib import Path

ROLES = [("AGENCY_MANAGER", "agency"), ("PROPERTY_ADMIN", "padmin"), ("PRESIDENT", "president"), ("SECRETARY", "secretary"), ("TREASURER", "treasurer"), ("MEMBER", "member"),
         ("AUDITOR", "auditor"), ("CARETAKER", "caretaker"), ("GUARD", "guard"), ("FLAT_OWNER", "owner2"), ("TENANT", "tenant"), ("OWNER_REP", "ownerrep")]
SAAS = [("SUPER_ADMIN", "super"), ("SAAS_ADMIN", "admin"), ("SAAS_FINANCE", "finance"), ("SAAS_SALES", "sales"), ("SAAS_USER", "support")]


def main() -> None:
    tmp = tempfile.mkdtemp()
    os.environ["DATABASE_URL"] = f"sqlite:///{tmp}/perm.db"
    os.environ["UPLOAD_DIR"] = f"{tmp}/up"
    os.environ["DEMO"] = "1"
    os.environ.pop("ENV", None)
    logging.disable(logging.CRITICAL)
    from fastapi.routing import APIRoute
    from fastapi.testclient import TestClient

    from . import seed
    from .main import app

    def flat(routes):
        for r in routes:
            if isinstance(r, APIRoute):
                yield r
            elif hasattr(r, "original_router"):
                yield from flat(r.original_router.routes)

    def kinds(r):
        names = set()

        def walk(d):
            for s in d.dependencies:
                names.add(getattr(s.call, "__qualname__", ""))
                walk(s)
        walk(r.dependant)
        return names
    seed.run()
    mods: dict[str, list[str]] = {}
    smods: dict[str, list[str]] = {}
    for r in flat(app.routes):
        if "GET" not in r.methods or "{" in r.path or not r.path.startswith("/api/"):
            continue
        k = kinds(r)
        mod = r.path.split("/")[2]
        if "property_ctx" in k:
            mods.setdefault(mod, []).append(r.path)
        elif any("require_saas" in x for x in k):
            smods.setdefault(mod, []).append(r.path)
    out = ["# Permissions matrix", "", "_Generated by `python -m app.permmatrix` against the seeded demo (Pro plan, Sunrise Tower). Do not edit by hand; regenerate after a permission change._", "",
           "## Building roles: which modules can each role read?", "",
           "Each cell: readable list endpoints / all list endpoints of the module (`-` = none). A resident role sees its own flat's records only; the number shows the endpoint is open, not that the whole building's data is.", ""]
    with TestClient(app) as c:
        def session(user: str, building: str | None = "Sunrise Tower"):
            r = c.post("/api/auth/login", json={"email": f"{user}@flatwise.demo", "password": "demo1234"}).json()
            h = {"Authorization": f"Bearer {r['token']}"}
            if building:
                h["X-Property-Id"] = str(next(p["id"] for p in r["properties"] if p["name"] == building))
            return h
        table: dict[str, dict[str, str]] = {m: {} for m in sorted(mods)}
        for role, user in ROLES:
            h = session(user)
            for m, paths in mods.items():
                ok = sum(1 for p in paths if c.get(p, headers=h).status_code == 200)
                table[m][role] = f"{ok}/{len(paths)}" if ok else "-"
        out.append("| module | " + " | ".join(r for r, _ in ROLES) + " |")
        out.append("|---|" + "---|" * len(ROLES))
        for m in sorted(table):
            out.append(f"| {m} | " + " | ".join(table[m][r] for r, _ in ROLES) + " |")
        out += ["", "## SaaS team: which console modules can each role read?", "", "| module | " + " | ".join(r for r, _ in SAAS) + " |", "|---|" + "---|" * len(SAAS)]
        for m in sorted(smods):
            cells = []
            for role, user in SAAS:
                h = session(user, None)
                ok = sum(1 for p in smods[m] if c.get(p, headers=h).status_code == 200)
                cells.append(f"{ok}/{len(smods[m])}" if ok else "-")
            out.append(f"| {m} | " + " | ".join(cells) + " |")
    out += ["", "## Role groups (backend/app/permissions.py)", ""]
    perms = Path(__file__).with_name("permissions.py").read_text()
    for line in perms.splitlines():
        if re.match(r"^[A-Z_]+ = ", line):
            out.append(f"- `{line}`")
    out += ["", "## Who may write, as written in each router", "", "Role sets passed to `ctx.need(...)` / `_gate(...)` and defined at the top of each router file (read from the source on each run).", "",
            "| router | role checks |", "|---|---|"]
    for f in sorted(Path(__file__).with_name("routers").glob("*.py")):
        src = f.read_text()
        consts = re.findall(r"^([A-Z][A-Z_]+) = (\{[^\n]*\}(?: \| [^\n]*)?|[A-Z_]+(?: \| [^\n]+)?)$", src, re.M)
        needs = sorted(set(re.findall(r"\.need\(([^)]*)\)", src)))
        if consts or needs:
            cs = "; ".join(f"`{n} = {v[:70].strip()}`" for n, v in consts if re.search(r"[A-Z]{3}", v) and not v.startswith('{"image/'))
            ns = ", ".join("`" + n.strip()[:40] + "`" for n in needs[:8])
            cell = f"{cs}{' · need: ' if cs and ns else ''}{ns}".replace("|", "\\|")
            if cell:
                out.append(f"| {f.stem} | {cell} |")
    out += ["", "SaaS staff with `SUPER_ADMIN` or `SAAS_ADMIN` pass every building-role check for support purposes (`Ctx.has` returns true for them). Every such access is a normal API call and appears in the audit log under their own name.", ""]
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
